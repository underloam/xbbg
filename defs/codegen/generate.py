def closed_set_members(
    table: dict[str, Any],
) -> list[tuple[str, str, list[str], str, bool]]:
    """Return (key, canonical value, aliases, doc, is_default) for one closed set.

    Rejects alias/canonical collisions and a missing or ambiguous default so a
    malformed defs edit fails codegen instead of silently producing a set that
    disagrees with the parser that owns it.
    """
    members: list[tuple[str, str, list[str], str, bool]] = []
    seen: dict[str, str] = {}
    for key, data in sorted_items(table):
        value = data["value"]
        aliases = data.get("aliases", [])
        if not isinstance(aliases, list) or not all(isinstance(item, str) for item in aliases):
            raise ValueError(f"{key}: aliases must be a list of strings")
        for spelling in [value, *aliases]:
            if spelling in seen:
                raise ValueError(f"{key}: spelling {spelling!r} already declared by {seen[spelling]}")
            seen[spelling] = key
        members.append((key, value, list(aliases), data["doc"], data.get("default") is True))
    defaults = [key for key, _, _, _, is_default in members if is_default]
    if len(defaults) != 1:
        raise ValueError(f"Closed set must define exactly one default, found {defaults}")
    return members


def escape_ts_string(value: str, quote: str) -> str:
    return value.replace("\\", "\\\\").replace(quote, f"\\{quote}")


def ts_literal(value: str, quote: str) -> str:
    """Quote a string the way the formatter would.

    The formatter prefers the package's configured quote but switches to the
    other one when that avoids escaping, so mirror that instead of emitting
    escapes the formatter would immediately undo.
    """
    alternate = '"' if quote == "'" else "'"
    chosen = alternate if quote in value and alternate not in value else quote
    return f"{chosen}{escape_ts_string(value, chosen)}{chosen}"


def ts_object_entry(key: str, literal: str) -> list[str]:
    """Render one object entry, wrapping over-width values like the formatter.

    A string literal cannot be split, so the formatter moves an over-width value
    onto its own indented line rather than leaving the entry long.
    """
    entry = f"  {key}: {literal},"
    if len(entry) <= TS_PRINT_WIDTH:
        return [entry]
    return [f"  {key}:", f"    {literal},"]


def ts_object_key(value: str, quote: str) -> str:
    """Quote an object key only when it is not a bare JS identifier.

    Mirrors the formatter's `as-needed` quoting so generated output is already
    formatted and `oxfmt --check` stays clean without running node from codegen.
    """
    if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", value):
        return value
    return ts_literal(value, quote)


def render_technical_typescript(defs: dict[str, Any], quote: str) -> list[str]:
    technical = defs["technical_analysis"]
    lines = ["", "export const TA_STUDIES: Readonly<Record<string, string>> = Object.freeze({"]
    for alias, attr in sorted_items(technical["studies"]):
        lines.extend(ts_object_entry(ts_object_key(alias, quote), ts_literal(attr, quote)))
    lines.extend(
        [
            "});",
            "",
            "type StudyDefaults = Readonly<Record<string, string | number>>;",
            "",
            "export const TA_DEFAULTS: Readonly<Record<string, StudyDefaults>> = Object.freeze({",
        ]
    )
