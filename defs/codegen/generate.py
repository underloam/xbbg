def render_typescript(defs: dict[str, Any], quote: str, *, langgraph: bool = False) -> str:
    """Render the shared closed-set vocabulary as TypeScript.

    Advertise `*_VALUES` in user-facing text so a documented set can never drift
    from the set the Rust engine actually accepts.
    """
    lines: list[str] = []
    lines.append(TS_HEADER)
    for section, plural, prefix, ts_type, set_doc in CLOSED_SETS:
        members = closed_set_members(defs[section])
        canonical = [value for _, value, _, _, _ in members]
        aliases = [alias for _, _, alias_list, _, _ in members for alias in alias_list]
        default_value = next(value for _, value, _, _, is_default in members if is_default)
        joined = ", ".join(ts_literal(value, quote) for value in canonical)
        lines.append("")
        lines.append(f"/** {set_doc} */")
        lines.append(f"export const {plural} = [{joined}] as const;")
        lines.append("")
        lines.append(f"/** {set_doc} */")
        lines.append(f"export type {ts_type} = (typeof {plural})[number];")
        if aliases:
            joined_aliases = ", ".join(ts_literal(alias, quote) for alias in aliases)
            lines.append("")
            lines.append("/** Extra spellings the engine also accepts, kept for compatibility. */")
            lines.append(f"export const {prefix}_ALIASES = [{joined_aliases}] as const;")
        lines.append("")
        lines.append("/** Value used when the caller omits it. */")
        default_literal = ts_literal(default_value, quote)
        lines.append(f"export const {prefix}_DEFAULT: {ts_type} = {default_literal};")
        lines.append("")
        lines.append("/** Canonical values as a list, for error text and tool descriptions. */")
        values_literal = ts_literal(", ".join(canonical), quote)
        lines.append(f"export const {prefix}_VALUES = {values_literal};")
        lines.append("")
        lines.append("/** Per-value documentation, keyed by canonical spelling. */")
        lines.append(f"export const {prefix}_DOCS: Readonly<Record<{ts_type}, string>> = {{")
        for _, value, _, doc, _ in members:
            lines.extend(ts_object_entry(ts_object_key(value, quote), ts_literal(doc, quote)))
        lines.append("};")
        lines.append("")
        lines.append("/** Canonical values keyed by their defs name. */")
        lines.append(f"export const {prefix}_BY_NAME = {{")
        for key, value, _, _, _ in members:
            lines.extend(ts_object_entry(key, ts_literal(value, quote)))
        lines.append("} as const;")
    constants = langgraph_contract(defs, python=False) if langgraph else defs["cdx_fields"]
    # The common closed-set renderer already supplies OverflowPolicy.
    constants = {name: value for name, value in constants.items() if name != "OVERFLOW_POLICIES"}
    lines.extend(render_typescript_constants(constants, quote))
    if langgraph:
        lines.append("")
        lines.append("export type BloombergToolName = (typeof BLOOMBERG_TOOL_NAMES)[number];")
        lines.append("export type ResultTruncationReason = (typeof TRUNCATION_REASON_ORDER)[number];")
    else:
        lines.extend(render_technical_typescript(defs, quote))
        for name, values in (
            ("VolSurfacePreset", defs["vol_surface_presets"]["values"]),
            ("IndexMemberField", defs["index_members"]["fields"]),
        ):
            literals = [ts_literal(value, quote) for value in values]
            inline = f"export type {name} = {' | '.join(literals)};"
            lines.append("")
            if len(inline) <= TS_PRINT_WIDTH:
                lines.append(inline)
            else:
                lines.extend([f"export type {name} =", *(f"  | {value}" for value in literals)])
                lines[-1] += ";"
    return "\n".join(lines) + "\n"


def render_rust_defs_contract(defs: dict[str, Any]) -> str:
    """Render tests binding defs to the hand-written parsers that own each set.

    The parsers live outside this generated file, so this is the only thing
    stopping a parser edit from silently invalidating every advertised value.
    """
    lines: list[str] = []
    lines.append("")
    lines.append("#[cfg(test)]")
    lines.append("mod defs_contract {")
    lines.append("    //! @generated - binds the hand-written parsers to the spellings")
    lines.append("    //! declared in defs/bloomberg.toml, in both directions.")
    lines.append("")
    lines.append("    use std::str::FromStr;")
    for section, rust_path, stem, has_default, has_display in RUST_CONTRACTS:
        members = closed_set_members(defs[section])
        default_value = next(value for _, value, _, _, is_default in members if is_default)
        spellings = [spelling for _, value, alias_list, _, _ in members for spelling in [value, *alias_list]]
        lines.append("")
        lines.append("    #[test]")
        lines.append(f"    fn {stem}_accepts_every_defs_spelling() {{")
        lines.append("        for spelling in [")
        for spelling in spellings:
            lines.append(f'            "{escape_rust_string(spelling)}",')
        lines.append("        ] {")
        lines.append("            assert!(")
        lines.append(f"                {rust_path}::from_str(spelling).is_ok(),")
        lines.append('                "defs/bloomberg.toml declares {spelling} but the parser rejects it"')
        lines.append("            );")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    #[test]")
        lines.append(f"    fn {stem}_defs_covers_every_variant() {{")
        lines.append("        // Non-exhaustive matches do not compile, so adding a variant to the")
        lines.append("        // enum without declaring it in defs breaks the build instead of")
        lines.append("        // silently leaving it out of every advertised value set.")
        lines.append(f"        fn canonical(value: {rust_path}) -> &'static str {{")
        lines.append("            match value {")
        for key, data in sorted_items(defs[section]):
            variant = rust_name(key, data)
            value = escape_rust_string(data["value"])
            lines.append(f'                {rust_path}::{variant} => "{value}",')
        lines.append("            }")
        lines.append("        }")
        lines.append("        for spelling in [")
        for _, value, _, _, _ in members:
            lines.append(f'            "{escape_rust_string(value)}",')
        lines.append("        ] {")
        lines.append("            assert_eq!(")
        lines.append(f"                canonical({rust_path}::from_str(spelling).unwrap()),")
        lines.append("                spelling,")
        lines.append('                "defs maps this spelling to a different variant than the parser does"')
        lines.append("            );")
        lines.append("        }")
        lines.append("    }")
        if has_display:
            canonical = [value for _, value, _, _, _ in members]
            lines.append("")
            lines.append("    #[test]")
            lines.append(f"    fn {stem}_display_matches_defs() {{")
            lines.append("        for canonical in [")
            for value in canonical:
                lines.append(f'            "{escape_rust_string(value)}",')
            lines.append("        ] {")
            lines.append("            assert_eq!(")
            lines.append(f"                {rust_path}::from_str(canonical)")
            lines.append("                    .unwrap()")
            lines.append("                    .to_string(),")
            lines.append("                canonical,")
            lines.append('                "the canonical defs value must be the value the engine emits"')
            lines.append("            );")
            lines.append("        }")
            lines.append("    }")
        if has_default:
            lines.append("")
            lines.append("    #[test]")
            lines.append(f"    fn {stem}_default_matches_defs() {{")
            lines.append("        assert_eq!(")
            lines.append(f'            {rust_path}::from_str("{escape_rust_string(default_value)}").unwrap(),')
            lines.append(f"            {rust_path}::default(),")
            lines.append('            "defs marks a different member as default than the parser does"')
            lines.append("        );")
            lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def is_stale(path: Path, expected: str) -> bool:
    if not path.exists():
        return True
    actual = path.read_text(encoding="utf-8")
    return actual != expected


def write_if_changed(path: Path, expected: str) -> bool:
    if not is_stale(path, expected):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8", newline="\n")
    return True


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Bloomberg API and LangGraph vocabulary from defs/bloomberg.toml"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether generated files are up to date (CI mode)",
    )
    return parser.parse_args(argv)


def _rustfmt(text: str) -> str:
    """Run rustfmt on generated Rust code so it matches cargo fmt output."""
    rustfmt = shutil.which("rustfmt")
    if rustfmt is None:
        return text
    result = subprocess.run(
        [rustfmt, "--edition", "2024"],
        input=text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    return result.stdout if result.returncode == 0 else text


def main(argv: list[str]) -> int:
    args = parse_args(argv)

    defs = load_defs(DEFS_PATH)
    validate_refs(defs)
    rust_text = _rustfmt(render_rust(defs) + render_rust_defs_contract(defs))
    python_text = render_python(defs)

    targets = [
        (RUST_OUT, rust_text),
        (PY_OUT, python_text),
        (PY_LANGGRAPH_OUT, render_langgraph_python(defs)),
        *((path, render_typescript(defs, quote, langgraph=langgraph)) for path, quote, langgraph in TS_OUTS),
    ]

    if args.check:
        stale: list[Path] = []
        for path, expected in targets:
            if is_stale(path, expected):
                stale.append(path)
        if stale:
            for path in stale:
                print(f"Stale generated file: {path.relative_to(ROOT)}")
            return 1
        print("Generated files are up to date.")
        return 0

    changed_any = False
    for path, expected in targets:
        changed = write_if_changed(path, expected)
        if changed:
            changed_any = True
            print(f"Updated {path.relative_to(ROOT)}")
        else:
            print(f"Unchanged {path.relative_to(ROOT)}")

    if not changed_any:
        print("No changes needed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
