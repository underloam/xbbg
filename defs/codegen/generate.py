def _python_tuple(name: str, values: list[str]) -> list[str]:
    """Render a str tuple the way `ruff format` would leave it.

    A single-element tuple keeps its required trailing comma on one line; longer
    tuples collapse when they fit in ruff's line length and otherwise explode one
    per line, so generated output never fights `ruff format --check`.
    """
    quoted = [f'"{escape_python_string(value)}"' for value in values]
    annotated = f"{name}: tuple[str, ...] = "
    if len(quoted) == 1:
        return [f"{annotated}({quoted[0]},)"]
    single_line = f"{annotated}({', '.join(quoted)})"
    if len(single_line) <= RUFF_LINE_LENGTH:
        return [single_line]
    return [f"{annotated}(", *(f"    {item}," for item in quoted), ")"]


